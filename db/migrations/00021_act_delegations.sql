-- The audit row names the agent as well as the person
------------------------------------------------------------------------------
-- §26.3's sentence has two halves and the schema only had one. `audit_log`
-- already records `user_id` (who) and `actor_role` (what authority they held);
-- this is what was acting on their behalf, and NULL is the ordinary case of a
-- person doing something themselves. A column that was never null would say
-- nothing.
--
-- WHY A DEFAULT AND NOT A PARAMETER ON record_audit_log
--
-- Every audit row today goes through `record_audit_log`, so widening its
-- signature would work. A default binds more: it also catches a writer that
-- inserts directly, including one written years from now by somebody who never
-- read this migration. Given that this table's claim is "nobody, including us,
-- can revise this", the mechanism that cannot be forgotten is the right one.
--
-- The GUC is transaction-local, set by the delegated request's transaction
-- alongside the two tenancy GUCs, and cleared by nothing because `set_config`
-- with `is_local` true ends at commit. It is NOT a third tenancy GUC: no policy
-- reads it, and nothing decides anything from it. It labels a row. That is the
-- distinction ENT-225 drew when it removed `app.billing_enabled`, which was a
-- deployment fact a Go check should have owned; who is acting is neither a
-- deployment fact nor a decision, and a trigger deep inside an UPDATE has no
-- other way to learn it.
alter table public.audit_log
  add column acting_agent text
  default nullif(current_setting('app.acting_agent', true), '');

