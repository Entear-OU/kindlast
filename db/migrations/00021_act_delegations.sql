-- Grants. THIS TABLE STARTS CLOSED (ENT-243).
------------------------------------------------------------------------------
-- 00002 set default privileges granting `kindlast_app` select, insert, update
-- and delete on every table the migrator creates, so this table arrives with
-- all four whatever is written below. Only an explicit revoke narrows it.
revoke all on public.act_delegations from kindlast_app;

-- Select, insert and update. NO DELETE: a delegation is revoked, not erased,
-- because what a customer was told an agent could do is evidence and evidence
-- that can be deleted is worth less than evidence that cannot.
grant select, insert, update on public.act_delegations to kindlast_app;

-- Nothing for `kindlast_agent`, `kindlast_ingest` or `kindlast_billing`. The
-- role that runs sweeps has no person to act for, and the two write-path roles
-- have no business near a credential that carries a human's authority.

-- MINTING: only for the person in the session, only in their organisation, and
-- only while they are a member of it.
--
-- The membership `exists` is the same clause every tenant policy carries, and
-- here it does a second job: an offboarded person cannot have a fresh
-- delegation minted for them even by a handler that still has their user id in
-- hand from earlier in the request.
create policy act_delegations_mint on public.act_delegations
  for insert to kindlast_app
  with check (
    org_id = (select current_setting('app.current_org_id')::uuid)
    and user_id = (select current_setting('app.current_user_id')::uuid)
    and exists (
      select 1 from public.memberships m
      where m.org_id = (select current_setting('app.current_org_id')::uuid)
        and m.user_id = (select current_setting('app.current_user_id')::uuid)
    )
  );

-- READING: your own, in the organisation you are acting in.
--
-- Not "everybody in the organisation": a delegation names one person's
-- authority, and an owner does not need to see which credentials exist for a
-- colleague in order to run the business. Revocation by somebody else is
-- ENT-230's follow-on if it is ever wanted, and it would be a deliberate
-- widening rather than an accident of this policy.
create policy act_delegations_select_own on public.act_delegations
  for select to kindlast_app
  using (
    org_id = (select current_setting('app.current_org_id')::uuid)
    and user_id = (select current_setting('app.current_user_id')::uuid)
    and exists (
      select 1 from public.memberships m
      where m.org_id = (select current_setting('app.current_org_id')::uuid)
        and m.user_id = (select current_setting('app.current_user_id')::uuid)
    )
  );

-- REVOKING: the same row set. The trigger above is what stops this being a way
-- to edit anything else.
create policy act_delegations_revoke on public.act_delegations
  for update to kindlast_app
  using (
    org_id = (select current_setting('app.current_org_id')::uuid)
    and user_id = (select current_setting('app.current_user_id')::uuid)
  )
  with check (
    org_id = (select current_setting('app.current_org_id')::uuid)
    and user_id = (select current_setting('app.current_user_id')::uuid)
  );

------------------------------------------------------------------------------
-- Resolution, for a caller who has no session yet
------------------------------------------------------------------------------
-- SECURITY DEFINER because the GUCs the policies read are not set: deciding
-- what to set them to is what this call is for. See the header.
--
-- ONE ANSWER FOR EVERY UNUSABLE DELEGATION. Expired, revoked, already redeemed
-- and never existed all return zero rows. Distinguishing them turns this into
-- an oracle for which credentials are real, and the caller has proved nothing
-- that entitles them to the difference. Same decision as `accept_invitation`
-- (00003) and `redeem_capability_token` (00015).
-- +goose StatementBegin
create function public.resolve_act_delegation(p_token_hash text)
returns table (user_id uuid, org_id uuid, acting_agent text)
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v public.act_delegations%rowtype;
begin
  select * into v
  from public.act_delegations d
  where d.token_hash = p_token_hash
    and d.revoked_at is null
    and d.expires_at > now()
  for update;

  if not found then
    return;
  end if;

  if v.single_use then
    if v.redeemed_at is not null then
      return;
    end if;
    -- Marked in the same statement that acts on it, under the row lock taken
    -- above, so two redemptions racing cannot both win.
    update public.act_delegations d
       set redeemed_at = now()
     where d.id = v.id;
  end if;

  user_id := v.user_id;
  org_id := v.org_id;
  acting_agent := v.acting_agent;
  return next;
end;
$function$;
-- +goose StatementEnd

revoke all on function public.resolve_act_delegation(text) from public;
grant execute on function public.resolve_act_delegation(text) to kindlast_app;

